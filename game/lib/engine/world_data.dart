/// Country profile (plan Module 10, starter data): the facts that change
/// how a life plays out there. Shown on the Me tab and when emigrating.
class CountryProfile {
  const CountryProfile({
    required this.lifeExpectancy,
    required this.healthcare,
    required this.drivingAge,
    required this.drinkingAge,
    required this.gamblingAge,
    required this.marriageEquality,
    required this.deathPenalty,
    required this.climate,
    required this.languages,
    required this.blurb,
    this.wage = 1.0,
    this.cost = 1.0,
    this.tuition = 1.0,
    this.draft = 'none',
    this.draftMonths = 0,
    this.retireAge = 65,
    this.safety = 'medium',
    this.culture = '',
    this.everyday = const [],
    this.local = const [],
  });

  final int lifeExpectancy;

  /// universal, insurance or out of pocket.
  final String healthcare;
  final int drivingAge;
  final int drinkingAge;
  final int gamblingAge;
  final bool marriageEquality;
  final bool deathPenalty;

  /// supportive, mixed or hostile (legal and social climate for LGBTQ+
  /// people, used gently in coming-out reactions and travel warnings).
  final String climate;
  final List<String> languages;
  final String blurb;

  // ---- Living there (docs/country-research.md) ----

  /// Pay and prices as multipliers of the game's base (United States = 1).
  /// Compressed so every country is playable; the order and gaps follow
  /// average wages and cost-of-living indices.
  final double wage;
  final double cost;

  /// Public university fees as a multiple of the base (0 = free).
  final double tuition;

  /// Military service: none, universal (men), selective (some are called,
  /// any gender) or lottery (men, chosen by lot).
  final String draft;
  final int draftMonths;
  final int retireAge;

  /// high, medium or low: how often crime touches everyday life.
  final String safety;
  final String culture;

  /// What living here is like, shown on the country card.
  final List<String> everyday;

  /// Yearly local moments: text, stat, change.
  final List<(String, String, int)> local;

  /// Plain words for the pay and price levels.
  String get payLabel => wage >= 0.8
      ? 'High'
      : wage >= 0.55
      ? 'Medium'
      : wage >= 0.3
      ? 'Low'
      : 'Very low';
  String get costLabel => cost >= 0.85
      ? 'High'
      : cost >= 0.65
      ? 'Medium'
      : 'Low';
  String get tuitionLabel => tuition == 0
      ? 'Free'
      : tuition < 0.3
      ? 'Low fees'
      : tuition < 0.7
      ? 'Moderate fees'
      : 'High fees';
  String get draftLabel => switch (draft) {
    'universal' => '$draftMonths months for men',
    'lottery' => 'By lottery for men',
    'selective' => 'Some are called up',
    _ => 'None',
  };

  /// Gambling is not legal for citizens when the age is 0.
  bool get gamblingBanned => gamblingAge == 0;
}

